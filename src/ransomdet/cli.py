import argparse
import json

from ransomdet import ablation, audit, baselines, data, features, final_model, generalization, split
from ransomdet.config import load_config
from ransomdet.runlog import timed


def cmd_download(cfg: dict, args: argparse.Namespace) -> None:
    for name, path in data.download_all(cfg).items():
        print(f"{name}: {path}")


def cmd_prepare(cfg: dict, args: argparse.Namespace) -> None:
    stats: dict = {}
    with timed(stats):
        if not args.dev or not (cfg["paths"]["processed"] / data.BH_PARQUET).exists():
            data.convert_bitcoinheist(cfg)
            data.convert_prices(cfg)
        data.make_dev_sample(cfg)
        split.build_splits(cfg, dev=args.dev)
        features.build_feature_table(cfg, dev=args.dev)
        result, body = audit.run_audit(cfg, dev=args.dev)
    result["run"] = stats

    reports = cfg["paths"]["reports"]
    reports.mkdir(parents=True, exist_ok=True)
    suffix = "_dev" if args.dev else ""
    header = [
        "# Data audit",
        "",
        "Generated by `ransomdet prepare" + (" --dev" if args.dev else "") + "`. "
        f"Runtime {stats['runtime_s']} s, peak memory {stats['peak_rss_mb']:.0f} MB.",
        "",
    ]
    if args.dev:
        header += ["Dev sample only: counts below are not the real dataset's.", ""]
    md = "\n".join(header + audit.summary_lines(result, cfg) + body)
    (reports / f"data_audit{suffix}.md").write_text(md, encoding="utf-8")
    (reports / f"data_audit{suffix}.json").write_text(
        json.dumps(result, indent=2, default=str), encoding="utf-8"
    )
    print(f"wrote {reports / f'data_audit{suffix}.md'}")


def cmd_train(cfg: dict, args: argparse.Namespace) -> None:
    baselines.run_baselines(cfg, dev=args.dev)


def cmd_evaluate(cfg: dict, args: argparse.Namespace) -> None:
    baselines.write_baselines_report(cfg, dev=args.dev)


def cmd_features(cfg: dict, args: argparse.Namespace) -> None:
    ablation.run_feature_ablation(cfg, dev=args.dev)


def cmd_final(cfg: dict, args: argparse.Namespace) -> None:
    final_model.run_final_model(cfg, dev=args.dev)


def cmd_generalize(cfg: dict, args: argparse.Namespace) -> None:
    generalization.run_generalization(cfg, dev=args.dev)


def cmd_explain(cfg: dict, args: argparse.Namespace) -> None:
    from ransomdet import explain

    explain.run_explanation(cfg, dev=args.dev)


def cmd_export_demo(cfg: dict, args: argparse.Namespace) -> None:
    from ransomdet import demo

    demo.export_demo(cfg, dev=args.dev)


COMMANDS = {
    "download": (cmd_download, "fetch BitcoinHeist, Ransomwhere and BTC/USD prices"),
    "prepare": (cmd_prepare, "build Parquet files, features, splits and the data audit"),
    "train": (cmd_train, "train the forward-in-time baselines and the old protocol"),
    "evaluate": (cmd_evaluate, "write the baselines report"),
    "features": (cmd_features, "run the feature-group ablation"),
    "final": (cmd_final, "tune, calibrate and test the final detector"),
    "generalize": (cmd_generalize, "leave-one-family-out and the Ransomwhere test"),
    "explain": (cmd_explain, "SHAP figures and the misses analysis"),
    "export-demo": (cmd_export_demo, "write the files the Gradio demo needs"),
}


def cmd_all(cfg: dict, args: argparse.Namespace) -> None:
    import subprocess
    import sys

    # One process per step, so each report's peak memory is that step's own.
    for name in COMMANDS:
        print(f"== {name}", flush=True)
        cmd = [sys.executable, "-m", "ransomdet.cli", "--config", args.config, name]
        subprocess.run(cmd + (["--dev"] if args.dev else []), check=True)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="ransomdet")
    parser.add_argument("--config", default="configs/default.yaml")
    sub = parser.add_subparsers(dest="command", required=True)
    for name, (_, text) in [*COMMANDS.items(), ("all", (cmd_all, "run every step in order"))]:
        p = sub.add_parser(name, help=text)
        p.add_argument("--dev", action="store_true", help="use the 200k-row dev sample")

    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    if args.command == "all":
        cmd_all(cfg, args)
    else:
        COMMANDS[args.command][0](cfg, args)


if __name__ == "__main__":
    main()
