import json

from ransomdet.runlog import timed
from ransomdet.train import fit_lgbm, load_split_frames, val_metrics


def run_feature_ablation(cfg: dict, dev: bool = False) -> dict:
    """Ablate the feature groups on validation with Baseline B settings; write the ablation report."""
    from ransomdet import features
    from ransomdet.reporting import fmt

    stats: dict = {}
    with timed(stats):
        train, val, _ = load_split_frames(cfg, dev)
        y_tr, y_val = train["is_ransom"].to_numpy(), val["is_ransom"].to_numpy()
        runs = {"base (6 original)": features.BASE}
        for g, cols in features.GROUPS.items():
            runs[f"base + {g}"] = features.BASE + cols
        runs["base + all groups"] = features.BASE + [c for cols in features.GROUPS.values() for c in cols]
        results = {}
        for name, feats in runs.items():
            b = fit_lgbm(
                cfg, features.feature_matrix(train, feats), y_tr, features.feature_matrix(val, feats), y_val
            )
            s = b.predict(features.feature_matrix(val, feats))
            results[name] = val_metrics(cfg, y_val, s, val["date"].to_numpy()) | {
                "trees": b.best_iteration,
                "features": feats,
            }
            print(f"{name}: val PR-AUC {results[name]['pr_auc']:.3f}")

        base = results["base (6 original)"]
        min_gain = cfg["feature_ablation"]["min_gain"]
        kept = [
            g
            for g in features.GROUPS
            if results[f"base + {g}"]["pr_auc"] - base["pr_auc"] > min_gain
            or results[f"base + {g}"]["recall_at_fpr"] - base["recall_at_fpr"] > min_gain
        ]
        chosen = features.BASE + [c for g in kept for c in features.GROUPS[g]]
        if kept and len(kept) < len(features.GROUPS):
            b = fit_lgbm(
                cfg, features.feature_matrix(train, chosen), y_tr, features.feature_matrix(val, chosen), y_val
            )
            s = b.predict(features.feature_matrix(val, chosen))
            results["chosen: base + " + "".join(kept)] = val_metrics(
                cfg, y_val, s, val["date"].to_numpy()
            ) | {
                "trees": b.best_iteration,
                "features": chosen,
            }

    reports = cfg["paths"]["reports"]
    suffix = "_dev" if dev else ""
    k, fpr_pct = cfg["metrics"]["top_k"], cfg["metrics"]["target_fpr"] * 100
    group_desc = {
        "A": "log scale",
        "B": "ratios",
        "C": "dollar value",
        "D": "round amounts",
        "E": "same-day percentiles",
    }
    table = [
        f"| Run | Val PR-AUC | Val recall at FPR {fpr_pct:g}% | Precision in top {k}/day | Trees |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, r in results.items():
        table.append(
            f"| {name} | {fmt(r['pr_auc'])} | {fmt(r['recall_at_fpr'])} | "
            f"{fmt(r['precision_at_k'])} | {r['trees']} |"
        )
    flag = " --dev" if dev else ""
    lines = [
        "# Feature groups",
        "",
        f"Generated by `ransomdet features{flag}`. Runtime {stats['runtime_s']} s, peak memory "
        f"{stats['peak_rss_mb']:.0f} MB.",
        "",
        *(["Dev sample only: these numbers are not the real results.", ""] if dev else []),
        f"Kept groups: {', '.join(f'{g} ({group_desc[g]})' for g in kept) or 'none'}. A group is kept "
        f"when adding it to the 6 base features raises validation PR-AUC or recall at {fpr_pct:g}% "
        f"FPR by more than {min_gain}. Chosen feature set ({len(chosen)} features): "
        + ", ".join(f"`{c}`" for c in chosen)
        + ".",
        "",
        "Everything here is scored on validation (Jul-Dec 2016). The test years are not used. "
        "Thresholds are set on validation itself, so recall at the FPR target is a ranking "
        "comparison, not a forecast.",
        "",
        *table,
        "",
        "Groups: A = log1p of income_btc, count, neighbors, length. B = income / neighbors "
        "(average payment) and count / neighbors. C = income in dollars at that day's close. "
        "D = distance of the dollar and BTC income to round amounts. E = rank among all addresses "
        "on the same day, read from per-day quantile tables saved to "
        "`data/processed/day_quantiles.parquet`. Trees split on order only, so group A changes a "
        "LightGBM model only through feature sampling and binning.",
        "",
    ]
    (reports / f"feature_ablation{suffix}.md").write_text("\n".join(lines), encoding="utf-8")
    payload = {"dev": dev, "kept_groups": kept, "chosen_features": chosen, "results": results, "run": stats}
    (reports / f"feature_ablation{suffix}.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"wrote {reports / f'feature_ablation{suffix}.md'}")
    return payload
